#!/usr/bin/env python3
"""Turn vendor/*.js and vendor/*.css into Sources/humanpls/Vendor.swift so the app has no resource files.
Run it again after you update a file in vendor/."""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
files = {
    "marked": "marked.min.js",
    "highlight": "highlight.min.js",
    "cssLight": "github.min.css",
    "cssDark": "github-dark.min.css",
}
out = ["// Generated by scripts/gen-vendor.py from vendor/. Do not edit.",
       "// marked 12.0.2 (MIT), highlight.js 11.9.0 (BSD-3-Clause).", "", "enum Vendor {"]
for name, fn in files.items():
    text = (root / "vendor" / fn).read_text(encoding="utf-8")
    assert '"""###' not in text, fn
    out.append(f"    static let {name} = ###\"\"\"\n{text}\n\"\"\"###")
out.append("}")
(root / "Sources/humanpls/Vendor.swift").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote Sources/humanpls/Vendor.swift")
